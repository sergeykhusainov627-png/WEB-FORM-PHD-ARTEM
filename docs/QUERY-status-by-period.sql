-- Статусы и типы данных в запросе QRY_PHD_MULT_DATA_COPY1 — ДИНАМИЧЕСКАЯ схема (через параметры-подстановки).
--
-- Почему динамика возможна: запрос уже получает список полей параметром :ANALYTIC_SET, и платформа
-- подставляет его ТЕКСТОМ в SQL. Значит в параметр можно передавать не только имена колонок, но и
-- целые выражения с псевдонимами — тогда число колонок определяется выбором на СЭ.
--
-- Единственное ограничение: :ANALYTIC_SET подставляется в ДВУХ местах — в SELECT и в GROUP BY.
-- Поэтому внутри него нельзя писать "AS "подпись"" (GROUP BY сломается). Решение — три параметра:
--
--   1) :ANALYTIC_SET  — аналитики БЕЗ псевдонимов (как сейчас): sold_to, zbur_lu, material, ...
--                        подставляется в SELECT и GROUP BY промежуточных CTE;
--   2) :EXTRA_FIELDS  — динамические агрегаты С псевдонимами, идут только в SELECT:
--        SUM(zsiu_indv) FILTER (WHERE period = 1 AND ztypeind = '0000000001') AS "Январь (План)",
--        MAX(zphd_stat) FILTER (WHERE period = 1 AND ztypeind = '0000000001') AS "Январь. Статус (План)",
--        ... по каждому выбранному периоду и каждому выбранному типу данных,
--        и то же для набора zvalue_sng ("... С нач.года");
--   3) :EXTRA_NAMES   — те же псевдонимы в кавычках, через запятую, без агрегатов —
--                        для финального SELECT, который проецирует результат Main_Data:
--        "Январь (План)", "Январь. Статус (План)", ...
--
-- Куда что встаёт в тексте запроса:
--   * в CTE (строки с ":ANALYTIC_SET," в SELECT и "GROUP BY :ANALYTIC_SET, zlib_indc, CALYEAR, PLANT")
--     :EXTRA_FIELDS добавляется в SELECT (это агрегаты, в GROUP BY их быть не должно),
--     а в GROUP BY добавляется zphd_stat — чтобы статусы не терялись (на каждый статус своя строка);
--   * в финальном SELECT вместо перечисления колонок идёт ":ANALYTIC_SET, :EXTRA_NAMES,".
--
-- Формула количества колонок (что и просил заказчик):
--   статусов = (число периодов) x (число выбранных типов данных),
--   значений = столько же, то есть всего по периодам 2 x 17 x K колонок, где K — число типов.
--
-- Что генерирует форма (по выбору пользователя на СЭ):
--   * список периодов фиксирован: месяцы 1..12, итоги 13=I кв., 14=II кв., 16=III кв.,
--     18=IV кв., 19=Год (те, что отмечены в "Поля для вывода");
--   * типы берутся из D_ZTYPEIND (многократный выбор, атрибут ID — например План = 0000000001);
--   * подписи типов — из наименований выбранных элементов отметки (для заголовков колонок).
--
-- Признак чек-бокса «Выводить информацию по статусам» (параметр :P_STATUS = 1/0):
--   * 1 — формируются и колонки статусов (MAX(zphd_stat) FILTER (...)), как описано выше;
--   * 0 — колонки статусов не формируются вовсе, а значения агрегируются по всем статусам
--         в общую сумму (в GROUP BY не добавляется zphd_stat).
