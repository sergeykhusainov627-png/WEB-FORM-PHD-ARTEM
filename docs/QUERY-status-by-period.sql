-- Статусы (ZPHD_STAT) в запросе QRY_PHD_MULT_DATA_COPY1 — вариант с группировкой по статусу.
--
-- Требования (ответы заказчика):
--   1) если статусов несколько — группировать по ним, статусы не должны теряться;
--   2) подписи колонок пока оставляем как есть;
--   3) статусы нужны и для набора «С нач.года» (для отчётности);
--   4) без чек-бокса «Выводить информацию по статусам» значения с разными статусами
--      агрегируются в общую сумму;
--   5) кроме периодов, статусы нужны отдельными столбцами для каждого выбранного
--      «Типа данных» (D_ZTYPEIND, справочник DICT_DATA_TYPE, «План» = 0000000001).
--
-- Как реализуется:
--   * в SELECT и GROUP BY добавляется выражение группировки по статусу;
--   * признак чек-бокса приходит параметром :P_STATUS (1/0). При 0 статусы схлопываются
--     в одну группу («Итого») — получается общая сумма, как в п.4; при 1 — отдельная
--     строка на каждый статус, как в п.1;
--   * «раздельные столбцы по типу данных» (п.5) — это pivot по ZTYPEIND: периодные колонки
--     дублируются на каждый тип данных. В статическом SQL список типов должен быть известен
--     заранее, поэтому нужен состав справочника DICT_DATA_TYPE (коды и подписи).
--
-- ШАГ 1. Параметр признака (в объекте Запрос): P_STATUS, строка, значение по умолчанию 0.
-- ШАГ 2. В SELECT ветки Main_Data добавить колонку статуса (после блока значений):

    CASE WHEN COALESCE(:P_STATUS, '0') = '1' THEN COALESCE(zphd_stat, '') ELSE 'Итого' END AS "Статус",

-- ШАГ 3. В GROUP BY ветки Main_Data добавить то же выражение группировки:

    CASE WHEN COALESCE(:P_STATUS, '0') = '1' THEN COALESCE(zphd_stat, '') ELSE 'Итого' END,

-- Тогда при выключенном чек-боксе все статусы суммируются в одну строку с подписью «Итого»,
-- а при включённом — каждый статус идёт своей строкой, и суммы считаются по каждому отдельно.
--
-- ШАГ 4 (после получения состава DICT_DATA_TYPE). Pivot периодов по типу данных:
--   для каждого кода типа T и каждого периода — своя колонка:

--     ROUND(SUM(zsiu_indv) FILTER (WHERE period = 1 AND ztypeind = '<T>'),6) AS "Январь (<Тип>)",
--     ... то же для всех 17 периодов и обоих наборов (zsiu_indv и zvalue_sng)
--     MIN(zphd_stat) FILTER (WHERE ztypeind = '<T>') AS "Статус. <Тип>",

-- ШАГ 5. Периоды (для справки, как сейчас устроено):
